// Q8: Write a function using arrow syntax that returns the square of a number.
// Objective: Create an arrow function that returns the square of a number.
// Explanation: The arrow function multiplies the input by itself and returns the result implicitly. It is called with two sample values. Concepts: arrow functions and expressions.


const square = (n) => n * n;

console.log(`Square of 4: ${square(4)}`);
console.log(`Square of 7: ${square(7)}`);
