// Q6: Demonstrate the use of arithmetic and logical operators with examples.

const a = 10;
const b = 3;

// Arithmetic Operators
console.log("Addition:", a + b);       // 13
console.log("Subtraction:", a - b);    // 7
console.log("Multiplication:", a * b); // 30
console.log("Division:", a / b);       // 3.3333333333333335
console.log("Modulus:", a % b);        // 1
console.log("Exponentiation:", a ** b);// 1000

// Logical Operators
const x = true;
const y = false;

console.log("Logical AND (x && y):", x && y); // false
console.log("Logical OR (x || y):", x || y);  // true
console.log("Logical NOT (!x):", !x);         // false
